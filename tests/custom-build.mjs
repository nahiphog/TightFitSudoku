import assert from 'node:assert/strict';
import { generateSlashes } from '../src/slashes.ts';
import { buildAttempt, validateBuild } from '../src/custom-build-engine.ts';
import { countSolutions } from '../src/solver.ts';
import { checkGrid } from '../src/check.ts';
let seed = 994812;
Math.random = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296);
const layout = generateSlashes(), cells = Array.from({ length: 36 }, (_, i) => i);
const base = { layout, selected: cells, minimum: 0, maximum: 100000 };
assert.equal(validateBuild(base), null);
assert.ok(validateBuild({ ...base, selected: [] }));
assert.ok(validateBuild({ ...base, selected: [36] }));
assert.ok(validateBuild({ ...base, minimum: 500, maximum: 300 }));
assert.ok(validateBuild({ ...base, minimum: -1 }));
assert.ok(validateBuild({ ...base, maximum: NaN }));
assert.ok(validateBuild({ ...base, layout: Array(36).fill(false) }));
const full = buildAttempt(base);
assert.ok(full.result);
assert.equal(full.result.walkthrough.rating, 0);
assert.equal(full.result.walkthrough.frames.length, 1);
assert.equal(checkGrid(layout, full.result.puzzle).solved, true);
const excluded = buildAttempt({ ...base, minimum: 300 });
assert.equal(excluded.unique, true);
assert.equal(excluded.rating, 0);
assert.equal(excluded.result, null, 'never accept a rating outside the range');
const sparse = buildAttempt({ ...base, selected: [0] });
assert.equal(sparse.unique, false);
assert.equal(sparse.result, null, 'never accept a non-unique pattern');
for (let n = 0; n < 12; n++) {
  const split = layout.indexOf(true);
  const selected = cells.filter(i => i !== (n === 0 ? split : n));
  const request = { ...base, selected };
  const snapshot = JSON.stringify(request);
  const attempt = buildAttempt(request);
  assert.ok(attempt.result);
  assert.equal(JSON.stringify(request), snapshot, 'do not change layout or clue mask');
  const result = attempt.result;
  assert.equal(countSolutions(layout, result.puzzle), 1);
  assert.deepEqual(result.layout, layout);
  result.puzzle.forEach((digits, i) => assert.equal(digits.length, selected.includes(i) ? layout[i] ? 2 : 1 : 0));
  assert.ok(result.walkthrough.rating >= request.minimum && result.walkthrough.rating <= request.maximum);
  assert.equal(checkGrid(layout, result.walkthrough.frames.at(-1).values).solved, true);
}
console.log('Custom builder passed: exact whole-cell clue mask, preserved slashes, unique solutions, bounded ratings, invalid inputs, non-unique rejection and completed walkthroughs.');
