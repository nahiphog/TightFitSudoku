import assert from 'node:assert/strict';
import { slashCounts } from '../src/slash-layout.ts';
import { validateBuild, buildAttempt } from '../src/custom-build-engine.ts';
import { countSolutions } from '../src/solver.ts';
const layout = ['111000', '000111', '111000', '000111', '111000', '000111'].join('').split('').map(c => c === '1');
const counts = slashCounts(layout);
assert.equal(counts.valid, true);
assert.equal(counts.total, 18);
assert.deepEqual(counts.rows, [3, 3, 3, 3, 3, 3]);
assert.deepEqual(counts.columns, [3, 3, 3, 3, 3, 3]);
assert.deepEqual(counts.regions, [3, 3, 3, 3, 3, 3]);
const removed = [...layout]; removed[0] = false;
assert.equal(slashCounts(removed).valid, false);
assert.deepEqual(slashCounts(removed).rows, [2, 3, 3, 3, 3, 3]);
assert.deepEqual(slashCounts(removed).columns, [2, 3, 3, 3, 3, 3]);
assert.deepEqual(slashCounts(removed).regions, [2, 3, 3, 3, 3, 3]);
const over = [...layout]; over[3] = true;
assert.equal(slashCounts(over).valid, false);
assert.deepEqual(slashCounts(over).rows, [4, 3, 3, 3, 3, 3]);
assert.deepEqual(slashCounts(over).regions, [3, 4, 3, 3, 3, 3]);
const wrong = [...removed]; wrong[6] = true;
assert.equal(slashCounts(wrong).total, 18);
assert.equal(slashCounts(wrong).valid, false, '18 total alone is insufficient');
assert.equal(slashCounts([]).valid, false);
assert.equal(slashCounts(Array(36).fill(false)).valid, false);
assert.equal(slashCounts(Array(36).fill(true)).valid, false);
const request = { layout, selected: Array.from({ length: 36 }, (_, i) => i).filter(i => i % 7 !== 0), minimum: 0, maximum: 100000 };
assert.ok(validateBuild({ ...request, layout: wrong }));
assert.throws(() => buildAttempt({ ...request, layout: wrong }), /three slashes/);
const result = buildAttempt(request).result;
assert.ok(result);
assert.deepEqual(result.layout, layout, 'never change manually chosen slashes');
assert.equal(countSolutions(layout, result.puzzle), 1);
result.puzzle.forEach((ds, i) => assert.equal(ds.length, request.selected.includes(i) ? layout[i] ? 2 : 1 : 0));
console.log('Manual slash layout tests passed: all 18 unit counts, missing/excess slashes, invalid 18-slash layouts, build guard and preserved manual layout.');
